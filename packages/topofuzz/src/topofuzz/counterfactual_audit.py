"""``topofuzz audit``: eval-axis counterfactual + per-node attribution.

F4's ``topofuzz ablate`` answers "which agent caused the flip across
TOPOLOGY perturbations?". F7's ``topofuzz audit`` answers the same
question on the INPUT axis: swap a demographic token in the eval
(Maria→Mario), run BOTH evals through the SAME variant, and attribute
any verdict flip to the upstream agent whose response was load-bearing.

The leave-one-out experiment shape is identical to F4. What differs:

* The "two runs we compare" share a variant and differ in the eval row.
* The hybrid prior is built from the COUNTERFACTUAL run's per-node
  outputs with the ablated node's response swapped for the CANONICAL
  run's response at the same node_id.
* The terminal re-execution uses the counterfactual eval's prompt
  (it's the counterfactual verdict we're trying to drag back to
  canonical).

Outputs
-------

* ``<run_dir>/audit.json`` — a sidecar mirroring ``ablation.json``.
  Schema fields documented under :class:`CounterfactualAuditSummary`.
* No new SQLite schema. Counterfactual cells are TRANSIENT in this
  pass — they live in memory for the duration of the audit and are
  summarised into the sidecar; the source run.sqlite is never
  mutated. (Future v1.1.x: optional persistence behind a flag.)

Cost contract
-------------

For a source run with V variants × E canonical evals × D dims:

* **Phase 1 (counterfactual cell generation):** up to V × E × D
  counterfactual evals × N agents per variant. Worst case
  ``V × E × D × N`` LLM calls. The cap is enforced by ``--max-cost-usd``
  via the same soft-warn-80% / hard-stop-100% protocol as ablation.
* **Phase 2 (leave-one-out):** for each (variant, canonical_eval,
  counterfactual_eval) triple that actually flipped, run an
  ablation experiment per upstream node. F4-equivalent cost shape.

Phase-1 cost dominates and is why ``--max-evals`` / ``--max-variants``
flags exist on the CLI: a typical buyer's first audit caps to a
2-variant × 3-eval × 1-dim slice (~tens of calls) before opening the
wallet for the full sweep.
"""

