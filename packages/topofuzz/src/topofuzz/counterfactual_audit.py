def validate_audit_source(run_dir: Path | str) -> dict:
    """Cheap, side-effect-free validation of a source run for audit.

    Checks manifest.json exists/parses, the source ran ``--jury-of-3``,
    and that no incompatible custom-builder / jury-kwargs fields are
    present — everything :func:`run_audit_pass` needs to refuse BEFORE
    it does any real work. No LLM calls and no ``run.sqlite`` reads
    happen here, so it is safe for the CLI to call this ahead of the
    interactive spend-confirmation prompt (ROB-5): an invalid or
    missing source run then errors out immediately instead of only
    AFTER the operator has answered "bills real LLM calls? [y/N]".

    Returns the parsed manifest dict (reused by :func:`run_audit_pass`
    so the source run is not re-read).

    Raises:
        AuditError: manifest missing/malformed; ``run_id`` missing;
            source run was not jury-of-3; custom prompt_builder or
            jury-construction fields present.
    """
    run_dir = Path(run_dir)
    manifest = _load_manifest(run_dir)
    run_id = manifest.get("run_id")
    if not isinstance(run_id, str) or not run_id:
        raise AuditError("manifest.run_id missing or not a string.")
    cli_args = manifest.get("cli_args") or {}
    if not isinstance(cli_args, dict):
        raise AuditError("manifest.cli_args missing or wrong shape.")
    if not cli_args.get("jury_of_3"):
        raise AuditError(
            "audit requires a jury-of-3 source run "
            "(manifest.cli_args.jury_of_3 != True). The leave-one-out "
            "re-judgments inherit the source run's judge-noise floor; "
            "without jury voting that floor is ~26 % per-judgment, which "
            "drowns the attribution signal. Re-run the source with "
            "`--jury-of-3` first."
        )

    # Same prompt-builder / jury-kwargs refusals as ablation.py so we
    # don't silently measure something different than the source.
    _PROMPT_BUILDER_KEYS = (
        "prompt_builder", "prompt_builder_module", "prompt_builder_path"
    )
    custom_builder = [k for k in _PROMPT_BUILDER_KEYS if cli_args.get(k)]
    if custom_builder:
        raise AuditError(
            "audit refuses to run on a source manifest that carries a "
            "custom prompt_builder field "
            f"({', '.join(custom_builder)}): the Phase-1 counterfactual "
            "cell generation would use the runner's default prompt builder, "
            "producing incomparable prompts."
        )
    _RECONSTRUCT_INCOMPATIBLE_KEYS = (
        "jury_temperature", "jury_max_tokens", "jury_seed",
        "jury_kwargs", "judge_kwargs",
    )
    incompatible = [k for k in _RECONSTRUCT_INCOMPATIBLE_KEYS if k in cli_args]
    if incompatible:
        raise AuditError(
            "audit refuses to run on a source manifest with unrecognised "
            f"jury-construction fields ({', '.join(incompatible)})."
        )
    return manifest


def run_audit_pass(
    run_dir: Path | str,
    *,
    dims: tuple[str, ...] = ALL_DIMS,
    max_cost_usd: float | None = None,
    max_variants: int | None = None,
    max_canonical_evals: int | None = None,
    llm_callable: Any = None,
    fixture_override: str | None = None,
    dry_run: bool = False,
    llm_cache: LLMCache | None = None,
) -> CounterfactualAuditSummary:
    """Run the counterfactual audit on a source run.

    Args:
        run_dir: An existing ``topofuzz run`` directory whose manifest
            says ``cli_args.jury_of_3 == True``.
        dims: Counterfactual dims to audit. Default is all four
            (name, zip, age, gender). Unknown dim strings raise eagerly.
        max_cost_usd: Soft-warn at 80 %, hard-stop at 100 %.
        max_variants: Cap variants from the source run included in the
            audit (helpful for cost containment; default unbounded).
        max_canonical_evals: Cap canonical eval rows per dim included
            in the audit (default unbounded).
        llm_callable: Async LLM call for both Phase-1 (counterfactual
            cell generation) and Phase-2 (leave-one-out terminal
            re-execution). Tests inject a stub. Phase-1 calls all nodes
            in the variant; Phase-2 calls only the terminal.
        fixture_override: Path that wins over ``cli_args.fixture`` when
            the fixture has moved on disk.
        dry_run: When True, every Phase-1 agent rollout and every jury
            vote is stubbed (Phase-2 terminal re-execs are also stubbed
            at the ``_audit_async`` site). Stays vendor-key-free: if the
            caller doesn't supply ``llm_callable``, a deterministic
            constant-response stub is injected at the
            :func:`run_audit_pass` entry. Counterfactual jury scores
            are pinned at 0.5 by the JuryJudge dry-run contract, so a
            Phase-1 "flip" appears whenever the source run's stored
            canonical_score was below the 0.5 verdict threshold (the
            stub at 0.5 reads as approve). The leave-one-out path is
            not meaningfully exercised — per-node attribution rows
            other than the terminal baseline are zero by construction.
            Use for plumbing tests + cost preflight only.
        llm_cache: Optional :class:`fuzzeval.cache.LLMCache` consulted by
            BOTH Phase-1 (via ``run_variant``) and Phase-2 (around the
            terminal re-execution ``_call_llm`` site). Caller is
            responsible for opening AND closing the cache — the CLI
            wraps both in a ``try/finally`` block; tests construct
            fresh per-tmp_path caches. Defaults to ``None`` (no
            caching, every call hits the vendor), which preserves the
            historical behavior for callers that haven't been updated.

    Raises:
        AuditError: manifest / run.sqlite missing / malformed; the source
            run was not jury-of-3; the fixture can't be loaded.
    """
    run_dir = Path(run_dir)
    manifest = validate_audit_source(run_dir)
    run_id = manifest.get("run_id")
    cli_args = manifest.get("cli_args") or {}

    # Validate dims eagerly so a CLI typo doesn't produce a silent no-op.
    for d in dims:
        if d not in ALL_DIMS:
            raise AuditError(
                f"Unknown counterfactual dim {d!r}. Supported: "
                f"{', '.join(ALL_DIMS)}."
            )

    # Reconstruct variants (mirrors ablation's path via confirm).
    from topofuzz.confirm import (
        ConfirmError,
        _load_eval_rows_by_id,
        _reconstruct_variants,
    )

    # Pass-2 MAJOR M1 fix: ``_reconstruct_variants`` raises
    # :class:`ConfirmError` on fixture-resolution failures (path missing,
    # wrong rng_seed, module-import failures inside the fixture).
    # ``ConfirmError`` is not an :class:`AuditError` subclass, so it
    # escaped the CLI's ``except AuditError`` and printed a raw Python
    # traceback. Wrap into AuditError so the CLI's existing handler
    # produces a clean exit-2 message. Independently corroborated by
    # the real-LLM smoke run during pass-2.
    try:
        by_hash = _reconstruct_variants(
            manifest, fixture_override=fixture_override
        )
    except ConfirmError as e:
        raise AuditError(
            f"audit: failed to reconstruct variants from manifest: {e}"
        ) from e
    variant_ids = list(manifest.get("variant_canonical_hashes") or [])
    if not variant_ids:
        raise AuditError(
            "manifest.variant_canonical_hashes is empty — source run "
            f"{run_dir.name!r} has no variants to audit."
        )
    if max_variants is not None:
        variant_ids = variant_ids[: max(0, int(max_variants))]
    missing = [v for v in variant_ids if v not in by_hash]
    if missing:
        raise AuditError(
            f"audit: {len(missing)} variant(s) from the manifest are not "
            "in the regenerated variant set — fixture or rng_seed drift. "
            f"Missing: {', '.join(h[:12] + '…' for h in missing)}."
        )

    canonical_eval_rows_by_id = _load_eval_rows_by_id(cli_args, run_dir)

    judge = _build_jury(cli_args, dry_run=dry_run)

    # Dry-run contract: every LLM call short-circuits to a stub (matches
    # the CLI flag's docstring + ``run_audit_pass``'s own ``dry_run``
    # docstring). Phase-2 already short-circuits inside ``_audit_async``;
    # Phase-1 agent rollouts traveled through ``run_variant`` which fell
    # back to LiteLLM when ``llm_callable=None``, hitting the vendor and
    # demanding a key. Inject the stub only when the caller didn't already
    # supply one — tests passing fake LLMs keep priority.
    effective_llm_callable = llm_callable
    if dry_run and effective_llm_callable is None:
        effective_llm_callable = _dry_run_llm_callable

    return asyncio.run(
        _audit_async(
            run_dir=run_dir,
            run_id=run_id,
            variant_ids=variant_ids,
            by_hash=by_hash,
            canonical_eval_rows_by_id=canonical_eval_rows_by_id,
            dims=dims,
            max_cost_usd=max_cost_usd,
            max_canonical_evals=max_canonical_evals,
            judge=judge,
            llm_callable=effective_llm_callable,
            dry_run=dry_run,
            llm_cache=llm_cache,
        )
    )


def _build_jury(cli_args: dict, *, dry_run: bool) -> Any:
    """Re-construct the JuryJudge from manifest cli_args (mirrors ablation)."""
    from fuzzeval.judge import JuryJudge

    rubric_path_str = cli_args.get("rubric")
    if rubric_path_str:
        rubric_path = Path(rubric_path_str)
    else:
        from topofuzz.cli import _packaged_default_rubric_path

        rubric_path = _packaged_default_rubric_path()

    kwargs: dict[str, Any] = {
        "rubric_path": rubric_path,
        "dry_run": dry_run,
    }
    resolved = cli_args.get("jury_models_resolved")
    verbatim = cli_args.get("jury_models")
    vendor_models: dict[str, str] | None = None
    allow_dup = False
    if isinstance(resolved, dict) and resolved:
        vendor_models = {str(k): str(v) for k, v in resolved.items()}
        allow_dup = len({m for m in vendor_models.values()}) != len(
            vendor_models
        )
        if isinstance(verbatim, str) and verbatim.strip():
            from topofuzz.cli import _parse_jury_models

            try:
                reparsed_models, reparsed_allow_dup = _parse_jury_models(
                    verbatim
                )
            except Exception as e:  # noqa: BLE001 — boundary: parser
                raise AuditError(
                    "manifest.cli_args.jury_models is unparseable while "
                    "jury_models_resolved is present: "
                    f"{e}"
                ) from e
            if (
                dict(reparsed_models) != dict(vendor_models)
                or reparsed_allow_dup != allow_dup
            ):
                raise AuditError(
                    "manifest.cli_args.jury_models and "
                    "jury_models_resolved disagree about the jury vendor "
                    "map. Resolve manually before re-running audit."
                )
    elif isinstance(verbatim, str) and verbatim.strip():
        from topofuzz.cli import _parse_jury_models

        vendor_models, allow_dup = _parse_jury_models(verbatim)

    if vendor_models is not None:
        kwargs["vendor_models"] = vendor_models
        kwargs["allow_duplicate_models"] = allow_dup
    # Pass-1 MAJOR M7 fix: the narrow `(FileNotFoundError, ValueError)`
    # tuple let real-world construction failures (missing env-var KeyError,
    # vendor-SDK ImportError, OSError on the rubric path, TypeError on a
    # malformed kwargs shape) crash with a raw Python traceback instead
    # of a clean AuditError with actionable triage copy. Broadened to
    # cover the shapes JuryJudge construction actually raises in the
    # field, with case-specific classification messages so the operator
    # knows whether to export a key, install an SDK, or fix the manifest.
    try:
        return JuryJudge(**kwargs)
    except KeyboardInterrupt:
        raise
    except KeyError as e:
        # Missing env var the JuryJudge construction looked up by name
        # (typically ANTHROPIC_API_KEY / OPENAI_API_KEY / GEMINI_API_KEY).
        raise AuditError(
            "failed to construct JuryJudge from manifest cli_args: "
            f"missing API key for vendor {e!r} — export "
            f"${str(e).strip(chr(39)).upper()}_API_KEY before running, "
            "or pass --dry-run to short-circuit the jury."
        ) from e
    except ImportError as e:
        raise AuditError(
            "failed to construct JuryJudge from manifest cli_args: "
            f"vendor SDK not installed ({e}). Install with "
            "`pip install topofuzz[full]` and retry."
        ) from e
    except (FileNotFoundError, OSError, ValueError, TypeError, RuntimeError) as e:
        raise AuditError(
            f"failed to construct JuryJudge from manifest cli_args: "
            f"{type(e).__name__}: {e}"
        ) from e


