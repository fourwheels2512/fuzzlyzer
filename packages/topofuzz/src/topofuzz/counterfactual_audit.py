AUDIT_SIDECAR_FILENAME = "audit.json"
# Pass-1 BLOCKER B1+B4 fix: bumped 1 → 2 because (a) by_swap_pair /
# by_dim ``total_pairs`` now means "Phase-1 attempts" not "Phase-2
# triples that produced a meaningful row" — same field name, different
# denominator semantics, so v1 readers would silently quote a wrong
# flip-rate; and (b) two new top-level fields (``unpriced_call_count``
# + ``unpriced_models``) appear so readers can detect cost-under-counting.
_AUDIT_SIDECAR_SCHEMA_VERSION = 2

# Outcome kinds for the leave-one-out per node. Persisted as strings so
# the sidecar reader doesn't depend on dataclass internals. Mirrors
# ablation.py's vocabulary so consumers (inspect, the PDF builder) can
# pattern-match across both sidecars.
_KIND_REEXECUTE_TERMINAL = "reexecute_terminal"
_KIND_SUBSTITUTE_TERMINAL = "substitute_terminal"
_KIND_SKIP_DOWNSTREAM = "skip_downstream"
_KIND_SKIP_NO_CANONICAL_OUTPUT = "skip_no_canonical_output"
_KIND_SKIP_NO_CF_OUTPUT = "skip_no_counterfactual_output"
_KIND_FAILED = "failed"

# Verdict-binarisation threshold; pinned to 0.5 to match ablation.
_VERDICT_THRESHOLD = 0.5

# Abort after N consecutive failures — same rationale as ablation.py
# (vendor hiccups are sporadic; programmer bugs cascade).
_MAX_CONSECUTIVE_FAILURES = 3

# Per-jury-call cost floor when reflection fails (mirrors ablation).
_JURY_COST_FALLBACK_FLOOR_USD = 0.03

# Per-LLM-call rough cost floor for Phase-1 counterfactual cells when
# the runner doesn't surface a per-call cost (e.g. dry-run, or vendor
# usage missing). Used only for cap accounting, NOT billing.
#
# Cost-tracker fallback discipline (Pass-2 RT MAJOR M3 + Pass-1 BLOCKER B4):
#   * Phase-1 cells are generated by every node in the variant, but most
#     buyer-fixtures run cheap Flash-tier models for the inner agents;
#     $0.01 is a reasonable order-of-magnitude floor.
#   * Phase-2 terminal re-execs target whatever the SOURCE run used at
#     the verdict node, which is frequently a premium ($0.03-$0.10/call
#     opus-tier) model. A shared $0.01 floor under-reports by 3-10× on
#     premium-tier verdict nodes — :data:`_PHASE2_TERMINAL_REEXEC_
#     FALLBACK_USD` below is the higher floor for that path.
# Neither constant is billing-accurate; both are advisory for cap
# accounting + the "EXCLUDES UNPRICED CALLS" disclosure.
_PHASE1_CELL_COST_FALLBACK_USD = 0.01

# Pass-2 RT MAJOR M3 fix: dedicated higher fallback for Phase-2
# terminal re-execution calls that fall through ``cost_for_call``
# (unpriced model OR missing usage tokens). Premium verdict-node models
# are $0.03-$0.10/call; $0.05 is the midpoint, deliberately closer to
# the upper end so a buyer's deposition-grade PDF doesn't quote a
# lower-bound the actual bill could 5× exceed. The Phase-1 fallback
# stays $0.01 because Phase-1 calls hit every inner agent, where Flash-
# tier pricing dominates.
_PHASE2_TERMINAL_REEXEC_FALLBACK_USD = 0.05

# Persisted-response-text cap (UTF-8 bytes), mirrors ablation.
_RESPONSE_TEXT_CAP = 8192


# Stub response text returned by :func:`_dry_run_llm_callable` for every
# Phase-1 agent rollout under ``dry_run=True``. Constant across all nodes,
# variants, and swaps so every counterfactual cell produces an identical
# terminal response — which is exactly the "no flips" invariant the
# Phase-2 dry_run short-circuit (audit_async ~line 1601) relies on.
_DRY_RUN_STUB_RESPONSE_TEXT = "[topofuzz audit --dry-run stub response]"


async def _dry_run_llm_callable(**kwargs: Any) -> dict[str, Any]:
    """LiteLLM-shaped stub injected into ``run_variant`` under dry_run.

    The audit CLI's ``--dry-run`` flag is documented as "every LLM call
    short-circuits to a stub" so a buyer can preflight the audit
    plumbing without exporting any vendor API key. The Phase-2 terminal
    re-exec path already short-circuits at ``_audit_async``; Phase-1
    agent rollouts went through :func:`topofuzz.runner.run_variant`,
    which fell back to LiteLLM when ``llm_callable=None`` — that
    fallback is what hit Gemini and broke the contract.

    Returns a dict shaped exactly like ``_extract_text_and_served`` +
    ``_extract_usage`` expect (LiteLLM ModelResponse-compatible). Zero
    usage tokens so cost accounting stays at $0 even before the
    ``_run_counterfactual_cell`` ``dry_run`` overwrite (defense-in-depth:
    if that overwrite is ever refactored out, the stub still won't
    inflate billing).
    """
    return {
        "choices": [
            {"message": {"content": _DRY_RUN_STUB_RESPONSE_TEXT}}
        ],
        "model": str(kwargs.get("model", "")),
        "usage": {"prompt_tokens": 0, "completion_tokens": 0},
    }


