def _aggregate(
    *,
    results: tuple[CounterfactualAuditResult, ...],
    dims: tuple[str, ...],
    n_canonical_pairs: int,
    n_flipping_pairs: int,
    total_cost: float,
    partial: bool,
    n_phase1_attempts_by_swap_pair: dict[tuple[str, str, str], int] | None = None,
    n_phase1_attempts_by_dim: dict[str, int] | None = None,
    n_flipping_pairs_by_swap_pair: dict[tuple[str, str, str], int] | None = None,
    n_flipping_pairs_by_dim: dict[str, int] | None = None,
    unpriced_call_count: int = 0,
    unpriced_models: tuple[str, ...] = (),
    dry_run: bool = False,
) -> CounterfactualAuditSummary:
    """Aggregate per-result rows into by_node / by_dim / by_swap_pair tables.

    Pass-1 BLOCKER B1 fix: ``n_phase1_attempts_by_swap_pair`` /
    ``n_phase1_attempts_by_dim`` carry the TRUE Phase-1 attempt counts
    (every cell we ran, not just flipping ones). When supplied, they
    are used as the denominator for ``by_swap_pair[*].total_pairs``,
    ``by_dim[*].total_pairs``, and ``by_dim[*].flip_rate_pct``.

    F7 BLOCKER fix: ``n_flipping_pairs_by_swap_pair`` /
    ``n_flipping_pairs_by_dim`` carry the TRUE Phase-1 flip counts.
    When supplied, they are used as the authoritative NUMERATOR for
    ``by_swap_pair[*].flipping_pairs`` and
    ``by_dim[*].flipping_pairs``. Without these, by_swap_pair and
    by_dim flip counts were derived from Phase-2 ``results[]``; when
    Phase 2 was cap-hit before any triple completed, that derivation
    collapsed every per-dim / per-swap flipping_pairs to 0 while the
    top-level ``n_flipping_pairs`` carried the (nonzero) Phase-1
    truth — surfacing as a contradictory PDF.

    The kwargs default to None for back-compat with existing tests that
    call ``_aggregate`` directly with only the meaningful-results
    skeleton; in that fallback path both numerator and denominator are
    rebuilt from ``results`` (preserves prior test contracts that pin
    attribution arithmetic without exercising the Phase-1 machinery).
    """
    if n_phase1_attempts_by_swap_pair is None:
        n_phase1_attempts_by_swap_pair = {}
    if n_phase1_attempts_by_dim is None:
        n_phase1_attempts_by_dim = {}
    # F7 BLOCKER fix: distinguish "kwarg not supplied at all" (test
    # back-compat: derive from results) from "kwarg supplied as empty
    # dict" (production zero-flip path: 0 is authoritative). The
    # ``_phase1_flip_kwargs_supplied`` flag preserves both contracts.
    _phase1_flip_kwargs_supplied = (
        n_flipping_pairs_by_swap_pair is not None
        or n_flipping_pairs_by_dim is not None
    )
    if n_flipping_pairs_by_swap_pair is None:
        n_flipping_pairs_by_swap_pair = {}
    if n_flipping_pairs_by_dim is None:
        n_flipping_pairs_by_dim = {}

    meaningful_kinds = (_KIND_REEXECUTE_TERMINAL, _KIND_SUBSTITUTE_TERMINAL)

    # by_node — across all dims + swaps.
    by_node: dict[str, dict[str, Any]] = {}
    for r in results:
        if r.kind not in meaningful_kinds:
            continue
        slot = by_node.setdefault(
            r.ablated_node_id,
            {
                "flips_closed": 0,
                "total_meaningful": 0,
                "attribution_pct": 0.0,
                "is_terminal": r.kind == _KIND_SUBSTITUTE_TERMINAL,
            },
        )
        slot["total_meaningful"] += 1
        if r.flip_closed:
            slot["flips_closed"] += 1
    for node_id, slot in by_node.items():
        if slot["total_meaningful"] > 0:
            slot["attribution_pct"] = round(
                100.0 * slot["flips_closed"] / slot["total_meaningful"], 2
            )

    # by_swap_pair — keyed by (dim, from, to) → flips_closed + by_node.
    by_swap_pair_tmp: dict[
        tuple[str, str, str], dict[str, Any]
    ] = {}
    for r in results:
        if r.kind not in meaningful_kinds:
            continue
        sp_key = (r.dim, r.from_token, r.to_token)
        slot = by_swap_pair_tmp.setdefault(
            sp_key,
            {
                "flipping_pairs": set(),
                "by_node": {},
            },
        )
        slot["flipping_pairs"].add(
            (r.variant_id, r.canonical_eval_id, r.counterfactual_eval_id)
        )
        per_node = slot["by_node"].setdefault(
            r.ablated_node_id,
            {"flips_closed": 0, "total_meaningful": 0, "attribution_pct": 0.0},
        )
        per_node["total_meaningful"] += 1
        if r.flip_closed:
            per_node["flips_closed"] += 1

    # Pass-1 BLOCKER B1 fix fallback: when no Phase-1 attempt maps are
    # supplied (test paths call _aggregate directly), reconstruct
    # denominators from the unique (variant, canonical_eval, cf_eval)
    # tuples observed in results. This preserves the prior test
    # contract that exercised attribution math without the Phase-1
    # attempt-count machinery.
    if not n_phase1_attempts_by_swap_pair:
        for r in results:
            if r.kind not in meaningful_kinds:
                continue
            sp_key = (r.dim, r.from_token, r.to_token)
            tmp = by_swap_pair_tmp.setdefault(
                sp_key, {"flipping_pairs": set(), "by_node": {}}
            )
            tmp.setdefault("_observed_triples", set()).add(
                (r.variant_id, r.canonical_eval_id, r.counterfactual_eval_id)
            )

    by_dim: dict[str, dict[str, Any]] = {d: {
        "flipping_pairs": 0,
        "total_pairs": 0,
        "flip_rate_pct": 0.0,
        "by_node": {},
    } for d in dims}

    # Ensure swap-pair keys from the Phase-1 attempt map are present
    # even when zero flips occurred (we still want to report
    # "Maria→Mario: 0/50" so the operator sees the dim was exercised).
    for sp_key in n_phase1_attempts_by_swap_pair.keys():
        by_swap_pair_tmp.setdefault(
            sp_key, {"flipping_pairs": set(), "by_node": {}}
        )

    by_swap_pair_json: dict[str, dict[str, Any]] = {}
    for sp_key, slot in by_swap_pair_tmp.items():
        dim, from_t, to_t = sp_key
        # F7 BLOCKER fix: numerator is the Phase-1 flip count when the
        # production maps were supplied; falls back to the Phase-2-
        # derived set length for test back-compat. Both branches use
        # ``len(slot["flipping_pairs"])`` for the Phase-2 contract.
        if _phase1_flip_kwargs_supplied:
            n_flip = n_flipping_pairs_by_swap_pair.get(sp_key, 0)
        else:
            n_flip = len(slot["flipping_pairs"])
        # Pass-1 BLOCKER B1 fix: denominator is the Phase-1 attempt
        # count when supplied; falls back to observed-triple count for
        # test paths.
        if sp_key in n_phase1_attempts_by_swap_pair:
            n_total = n_phase1_attempts_by_swap_pair[sp_key]
        else:
            n_total = len(slot.get("_observed_triples", set()))
        per_node_table = slot["by_node"]
        for nid, pn in per_node_table.items():
            if pn["total_meaningful"] > 0:
                pn["attribution_pct"] = round(
                    100.0 * pn["flips_closed"] / pn["total_meaningful"], 2
                )
        flat_key = _swap_pair_key(dim, from_t, to_t)
        by_swap_pair_json[flat_key] = {
            "dim": dim,
            "from_token": from_t,
            "to_token": to_t,
            "flipping_pairs": n_flip,
            "total_pairs": n_total,
            "by_node": per_node_table,
        }

    # Pass-1 MAJOR M4 fix: rebuild by_dim[*].by_node directly from
    # results, deduplicating by the (variant, canonical_eval, cf_eval,
    # ablated_node_id) tuple. The prior code accumulated from
    # by_swap_pair_tmp.by_node; when a single flipping triple was
    # counted under TWO swap-pairs within the same dim (e.g. an eval
    # row carrying both "Greg Walsh" AND a second recognised
    # Bertrand-Mullainathan name), its ablation rows got double-
    # counted in the dim aggregate.
    by_dim_seen: dict[tuple[str, str, str, str, str], bool] = {}
    for r in results:
        if r.kind not in meaningful_kinds:
            continue
        dim = r.dim
        if dim not in by_dim:
            continue
        dedup_key = (
            dim, r.variant_id, r.canonical_eval_id,
            r.counterfactual_eval_id, r.ablated_node_id,
        )
        if dedup_key in by_dim_seen:
            continue
        by_dim_seen[dedup_key] = True
        slot_node = by_dim[dim]["by_node"].setdefault(
            r.ablated_node_id,
            {
                "flips_closed": 0,
                "total_meaningful": 0,
                "attribution_pct": 0.0,
            },
        )
        slot_node["total_meaningful"] += 1
        if r.flip_closed:
            slot_node["flips_closed"] += 1

    # by_dim.flipping_pairs: Phase-1 flip count per dim when the
    # production maps were supplied (F7 BLOCKER fix); falls back to
    # Phase-2-derived unique-triple count for test back-compat. The
    # Phase-2 derivation collapses to 0 whenever Phase 2 is cap-hit
    # before any triple produces meaningful results — the exact
    # contradiction the maps were threaded in to prevent.
    if _phase1_flip_kwargs_supplied:
        for d in dims:
            by_dim[d]["flipping_pairs"] = n_flipping_pairs_by_dim.get(d, 0)
    else:
        by_dim_flipping_triples: dict[str, set[tuple[str, str, str]]] = {
            d: set() for d in dims
        }
        for r in results:
            if r.kind not in meaningful_kinds:
                continue
            if r.dim not in by_dim_flipping_triples:
                continue
            by_dim_flipping_triples[r.dim].add(
                (r.variant_id, r.canonical_eval_id, r.counterfactual_eval_id)
            )
        for d in dims:
            by_dim[d]["flipping_pairs"] = len(by_dim_flipping_triples[d])

    for d, slot in by_dim.items():
        # Pass-1 BLOCKER B1 fix: by_dim total_pairs is the Phase-1
        # attempt count for the dim. Without it, fall back to summing
        # per-swap-pair denominators (back-compat for test paths).
        if d in n_phase1_attempts_by_dim:
            slot["total_pairs"] = n_phase1_attempts_by_dim[d]
        else:
            slot["total_pairs"] = sum(
                v["total_pairs"]
                for v in by_swap_pair_json.values()
                if v["dim"] == d
            )
        if slot["total_pairs"] > 0:
            slot["flip_rate_pct"] = round(
                100.0 * slot["flipping_pairs"] / slot["total_pairs"], 2
            )
        for nid, pn in slot["by_node"].items():
            if pn["total_meaningful"] > 0:
                pn["attribution_pct"] = round(
                    100.0 * pn["flips_closed"] / pn["total_meaningful"], 2
                )

    n_meaningful = sum(
        1 for r in results if r.kind in meaningful_kinds
    )

    return CounterfactualAuditSummary(
        n_canonical_pairs=n_canonical_pairs,
        n_flipping_pairs=n_flipping_pairs,
        n_ablation_points=len(results),
        n_ablation_points_meaningful=n_meaningful,
        dims=dims,
        total_cost_usd=total_cost,
        partial=partial,
        by_dim=by_dim,
        by_swap_pair=by_swap_pair_json,
        by_node=by_node,
        unpriced_call_count=unpriced_call_count,
        unpriced_models=unpriced_models,
        results=results,
        dry_run=dry_run,
    )
