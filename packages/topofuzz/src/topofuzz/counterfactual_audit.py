def read_audit_sidecar(run_dir: Path | str) -> dict | None:
    """Return ``<run_dir>/audit.json`` parsed, or ``None`` when absent."""
    path = Path(run_dir) / AUDIT_SIDECAR_FILENAME
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        raise AuditError(
            f"{AUDIT_SIDECAR_FILENAME} in {Path(run_dir).name!r} is "
            f"present but unreadable / not valid JSON: {e}"
        ) from e
    if not isinstance(data, dict):
        raise AuditError(
            f"{AUDIT_SIDECAR_FILENAME} in {Path(run_dir).name!r} is "
            "not a JSON object."
        )
    # Pass-2 BLOCKER B1 fix + Pass-2 MAJOR M3 fix: enforce schema_version
    # at every read. Without this gate, a v1 sidecar from a partner /
    # cached evidence vault / hand-edited file would render with v2-shape
    # code, silently quoting wrong denominators (v1 quoted Phase-2
    # flipping triples; v2 quotes Phase-1 attempts — same field name,
    # different semantics) in the PDF + headline. Mirrors the
    # `attest.py` ~L498 PAYLOAD_SCHEMA_VERSION shape.
    observed = data.get("schema_version")
    if observed != _AUDIT_SIDECAR_SCHEMA_VERSION:
        raise AuditError(
            f"audit.json schema_version is {observed!r}, expected "
            f"{_AUDIT_SIDECAR_SCHEMA_VERSION}. Older sidecars carry "
            "different denominator semantics (v1 quoted Phase-2 "
            "flipping triples; v2 quotes Phase-1 attempts) — rerun "
            "`topofuzz audit` against the source run to regenerate."
        )
    return data


def _atomic_write_text(target: Path, text: str) -> None:
    """Same atomic temp+replace pattern as ablation._atomic_write_text.

    Inline rather than factored to a shared module per minimalist scope;
    when a third sidecar writer lands the right move is to lift both
    out together (paired contract: response-text cap + atomic write).
    """
    target = Path(target)
    fd, tmp_name = tempfile.mkstemp(
        prefix=f".{target.name}.tmp.",
        dir=str(target.parent),
        suffix="",
    )
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.write(text)
        try:
            os.replace(tmp_path, target)
        except PermissionError as e:
            raise AuditError(
                f"Could not write {target.name}: {e}. On Windows this "
                "usually means another process (antivirus, file indexer) "
                "has the file open. Retry, or pass a different run_dir."
            ) from e
    except BaseException:
        try:
            tmp_path.unlink()
        except OSError:
            pass
        raise


def _truncate_response(text: str | None) -> str | None:
    if text is None:
        return None
    encoded = text.encode("utf-8")
    if len(encoded) <= _RESPONSE_TEXT_CAP:
        return text
    cut = _RESPONSE_TEXT_CAP
    while cut > 0 and (encoded[cut] & 0xC0) == 0x80:
        cut -= 1
    return encoded[:cut].decode("utf-8", errors="ignore") + "…[truncated]"


def _swap_pair_key(dim: str, from_token: str, to_token: str) -> str:
    """Flattened JSON key for the by_swap_pair table.

    Tuple keys can't be JSON-serialised; we use a stable ``dim|from|to``
    string. Pipe is non-conflicting with any token we ship (no pipe in
    Bertrand-Mullainathan names, ZIPs, ages, or gender labels). A user
    whose custom swap table contains pipes would collide; we explicitly
    document and assert against that at write time.
    """
    if "|" in dim or "|" in from_token or "|" in to_token:
        raise AuditError(
            f"swap-pair key contains a pipe character (dim={dim!r}, "
            f"from={from_token!r}, to={to_token!r}); audit.json key "
            "shape requires a non-pipe vocabulary."
        )
    return f"{dim}|{from_token}|{to_token}"


def _write_audit_sidecar(run_dir: Path, summary: CounterfactualAuditSummary) -> None:
    # Pass-RT-B1 fix (dual-audit, 2026-05-17): refuse to overwrite a
    # real-money sidecar with a dry-run one. Scenario the RT auditor
    # surfaced: a buyer runs ``topofuzz audit`` (real, $4 spend, clean
    # audit.json), then later runs ``topofuzz audit --dry-run`` (demo,
    # forgotten-key retry, etc.). Without this gate the real sidecar
    # gets clobbered with stub data and a subsequent ``topofuzz
    # publish --counterfactual-card`` renders procurement-grade PDF
    # off the stub. The guard mirrors v2 sidecars that pre-date the
    # ``dry_run`` field by defaulting ``dry_run=False`` on missing —
    # they were always real audits, so treating them as real here is
    # safe. The reverse direction (real over dry-run) is always
    # allowed: a buyer who exports keys after a dry-run preflight
    # should be able to run the real pass without manually deleting
    # the preflight sidecar.
    target_path = Path(run_dir) / AUDIT_SIDECAR_FILENAME
    if summary.dry_run and target_path.exists():
        try:
            existing = json.loads(target_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            existing = None
        if isinstance(existing, dict) and not existing.get("dry_run", False):
            raise AuditError(
                "audit refuses to overwrite an existing real-money "
                f"{AUDIT_SIDECAR_FILENAME} with a --dry-run sidecar. "
                "A subsequent `topofuzz publish` would render a "
                "procurement PDF off stub data. Delete the existing "
                "sidecar manually if you really want to clobber it, "
                "or omit --dry-run to re-run the audit for real."
            )

    payload = {
        "schema_version": _AUDIT_SIDECAR_SCHEMA_VERSION,
        "n_canonical_pairs": summary.n_canonical_pairs,
        "n_flipping_pairs": summary.n_flipping_pairs,
        "n_ablation_points": summary.n_ablation_points,
        "n_ablation_points_meaningful": summary.n_ablation_points_meaningful,
        "dims": list(summary.dims),
        "total_cost_usd": summary.total_cost_usd,
        "partial": summary.partial,
        # Pass-RT-B1 fix: dry_run is an additive field — schema_version
        # stays at 2 (v2 readers default ``data.get("dry_run", False)``
        # to False, which is correct for any pre-fix sidecar since
        # those were always produced by real audit runs).
        "dry_run": summary.dry_run,
        "by_dim": summary.by_dim,
        "by_swap_pair": summary.by_swap_pair,
        "by_node": summary.by_node,
        # Pass-1 BLOCKER B4 fix: surface unpriced-call accounting so a
        # buyer reading audit.json can tell "total_cost_usd = $0.42"
        # from "total_cost_usd = $0.42 LOWER BOUND because N calls hit
        # unpriced models".
        "unpriced_call_count": summary.unpriced_call_count,
        "unpriced_models": list(summary.unpriced_models),
        "results": [
            {
                "variant_id": r.variant_id,
                "canonical_eval_id": r.canonical_eval_id,
                "counterfactual_eval_id": r.counterfactual_eval_id,
                "dim": r.dim,
                "from_token": r.from_token,
                "to_token": r.to_token,
                "ablated_node_id": r.ablated_node_id,
                "kind": r.kind,
                "canonical_score": r.canonical_score,
                "original_cf_score": r.original_cf_score,
                "new_cf_score": r.new_cf_score,
                "flip_closed": r.flip_closed,
                "cost_usd": r.cost_usd,
                "new_terminal_response_text": r.new_terminal_response_text,
                "jury_votes": list(r.jury_votes),
            }
            for r in summary.results
        ],
    }
    _atomic_write_text(
        run_dir / AUDIT_SIDECAR_FILENAME,
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
    )


