@dataclass(frozen=True)
class CounterfactualAuditResult:
    """One leave-one-out experiment on the counterfactual axis.

    Field names mirror :class:`topofuzz.ablation.AblationResult` where
    semantics overlap, and add ``dim`` + ``from_token`` + ``to_token``
    so the sidecar reads as plain English without a legend.
    """

    variant_id: str
    canonical_eval_id: str
    counterfactual_eval_id: str
    dim: str
    from_token: str
    to_token: str
    ablated_node_id: str
    kind: str
    canonical_score: float | None
    original_cf_score: float | None
    new_cf_score: float | None
    flip_closed: bool | None
    cost_usd: float
    new_terminal_response_text: str | None
    jury_votes: tuple[dict[str, Any], ...]


@dataclass(frozen=True)
class CounterfactualAuditSummary:
    """``topofuzz audit`` summary, returned by :func:`run_audit_pass`.

    Attributes:
        n_canonical_pairs: count of Phase-1 counterfactual cells run
            (one per ``(variant, canonical_eval, swap)`` tuple). A
            single ``(variant, canonical_eval, dim)`` may produce
            multiple Phase-1 cells when its dim emits multiple swaps
            (e.g. a name-dim row containing two B-M names yields two
            swap rows, each bumping the counter). Pass-1 MINOR Mi4
            fix: prior docstring said "distinct
            ``(variant, canonical_eval, dim)`` we generated a swap for"
            — that drifted from the implementation, which increments
            per Phase-1 cell, not per dim. Mirror semantics with
            ``by_dim``/``by_swap_pair``'s ``total_pairs`` field
            (also Phase-1-attempt count post-B1).
        n_flipping_pairs: subset whose counterfactual verdict diverged
            from canonical (the Phase-2 input set).
        n_ablation_points: total leave-one-out experiments attempted
            (incl. skipped).
        n_ablation_points_meaningful: experiments that produced a
            re-judged score (kind in {reexecute_terminal,
            substitute_terminal}).
        dims: dims requested in this audit, in request order.
        total_cost_usd: real-LLM spend across both phases.

            **Pass-2 MINOR Mi3 (CR) note:** ``substitute_terminal`` rows
            under ``counterfactual_audit`` contribute $0 (deterministic
            synthesis per Pass-1 MAJOR M8 — the canonical text is
            grafted directly into the verdict slot, no LLM call); F4's
            parallel ``ablation.py`` surface charges the jury floor for
            its terminal-substitute path. A side-by-side
            ``total_cost_usd`` comparison between ``audit.json`` and
            ``ablation.json`` under-counts F7 by roughly
            ``$0.03 × n_substitute_terminal``.

            **Pass-2 RT MAJOR M3 note:** unpriced Phase-2 terminal
            re-execs charge :data:`_PHASE2_TERMINAL_REEXEC_FALLBACK_USD`
            ($0.05), NOT the Phase-1 fallback ($0.01). When
            ``unpriced_call_count > 0`` the total is a LOWER BOUND and
            the gap could be ~5× larger on premium verdict-node models.
        partial: True when ``--max-cost-usd`` hard-stopped early.
        by_dim: ``{dim: {flipping_pairs, total_pairs,
            flip_rate_pct, by_node}}`` — the dim-level disparate-impact
            sample summary. **Pass-1 BLOCKER B1 fix:** ``total_pairs``
            is the count of Phase-1 ATTEMPTS for that dim (i.e. how
            many canonical-vs-counterfactual cells we ran), NOT the
            count of Phase-2 ablation triples. The prior denominator
            was structurally wrong — ``triple_seen`` was built only
            from flipping triples, so ``flip_rate_pct`` always
            collapsed to ~100%.
        by_swap_pair: ``{(dim, from_token, to_token): {flipping_pairs,
            total_pairs, by_node}}`` — keyed by the exact substitution
            so the PDF can render "Maria→Mario flipped 12/50; risk_agent
            64%". JSON-serialised with a flattened key shape.
            ``total_pairs`` same Phase-1-attempt semantics as
            ``by_dim``'s field (Pass-1 BLOCKER B1 fix).
        by_node: ``{node_id: {flips_closed, total_meaningful,
            attribution_pct, is_terminal}}`` — the audit-wide
            per-node attribution table that the PDF leads with.
        unpriced_call_count: count of Phase-2 terminal re-execution
            calls whose model wasn't in the cost rate-table (or whose
            usage tokens were missing). Pass-1 BLOCKER B4 fix:
            ``total_cost_usd`` is a LOWER BOUND when this is nonzero,
            because each unpriced call adds the fallback floor
            (:data:`_PHASE1_CELL_COST_FALLBACK_USD`) instead of the
            actual vendor spend.
        unpriced_models: set of model IDs that triggered the unpriced-
            call fallback. Surfaced to the PDF + CLI so operators
            know which vendor's rate table needs adding to
            ``fuzzeval.costest``.
        dry_run: True when the audit pass ran with ``--dry-run``. Serialized
            into ``audit.json`` so downstream consumers (``topofuzz publish
            --counterfactual-card`` first; later: in-memory dashboards)
            can refuse to render procurement-grade artifacts off
            stub data. Defaults to False on existing v2 sidecars (the
            field is additive — schema_version stays at 2).
        results: per-experiment rows.
    """

    n_canonical_pairs: int
    n_flipping_pairs: int
    n_ablation_points: int
    n_ablation_points_meaningful: int
    dims: tuple[str, ...]
    total_cost_usd: float
    partial: bool
    by_dim: dict[str, dict[str, Any]]
    by_swap_pair: dict[str, dict[str, Any]]
    by_node: dict[str, dict[str, Any]]
    unpriced_call_count: int
    unpriced_models: tuple[str, ...]
    results: tuple[CounterfactualAuditResult, ...]
    # Pass-RT-B1 fix (dual-audit, 2026-05-17): carry the dry_run flag
    # through to the sidecar so ``publish`` can refuse to render a
    # procurement PDF off stub data. Defaulted False to keep the
    # constructor signature backward-compatible for existing call sites
    # that don't yet supply the flag (test helpers, in-memory callers).
    dry_run: bool = False


