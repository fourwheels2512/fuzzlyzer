def _load_manifest(run_dir: Path) -> dict:
    try:
        return json.loads(
            (run_dir / "manifest.json").read_text(encoding="utf-8")
        )
    except FileNotFoundError as e:
        raise AuditError(
            f"manifest.json missing in run_dir {run_dir.name!r}"
        ) from e
    except json.JSONDecodeError as e:
        raise AuditError(
            f"manifest.json in {run_dir.name!r} is not valid JSON: {e}"
        ) from e


def _load_cell_outputs(
    run_dir: Path, variant_id: str, eval_id: str
) -> list[dict[str, Any]] | None:
    db_path = run_dir / "run.sqlite"
    if not db_path.exists():
        raise AuditError(
            f"run.sqlite not found under run_dir={run_dir!r}"
        )
    con = sqlite3.connect(str(db_path))
    try:
        row = con.execute(
            "SELECT node_outputs_json FROM cells "
            "WHERE variant_id=? AND eval_id=?",
            (variant_id, eval_id),
        ).fetchone()
    finally:
        con.close()
    if row is None:
        return None
    try:
        outputs = json.loads(row[0])
    except (TypeError, json.JSONDecodeError) as e:
        raise AuditError(
            f"node_outputs_json malformed for variant={variant_id[:8]} "
            f"eval={eval_id}: {e}"
        ) from e
    if not isinstance(outputs, list):
        raise AuditError(
            f"node_outputs_json for variant={variant_id[:8]} eval="
            f"{eval_id} is not a JSON array."
        )
    # Pass-1 MAJOR M1 fix: per-element validation (ported from
    # ablation._load_cell_outputs lines 407-412). The dict-comprehension
    # at the call site `{o.get("node_id"): o for o in ...}` silently
    # skips non-dict entries via `isinstance(o, dict)`, which would let
    # a malformed cell with strings / numbers / nulls in the array slip
    # past undetected — the audit would proceed but with a smaller-
    # than-expected node-id map, producing skip rows the operator can't
    # explain. Refuse eagerly so the malformed cell surfaces with the
    # offending index instead.
    for i, item in enumerate(outputs):
        if not isinstance(item, dict):
            raise AuditError(
                f"node_outputs_json[{i}] for variant={variant_id[:8]} "
                f"eval={eval_id} is {type(item).__name__}, expected dict."
            )
    return outputs


def _load_judge_score(
    run_dir: Path, variant_id: str, eval_id: str
) -> float | None:
    """Read the cell's judge score (continuous-first, binary fallback)."""
    db_path = run_dir / "run.sqlite"
    con = sqlite3.connect(str(db_path))
    try:
        row = con.execute(
            "SELECT score_value, passed FROM judge_results "
            "WHERE variant_id=? AND eval_id=?",
            (variant_id, eval_id),
        ).fetchone()
    finally:
        con.close()
    if row is None:
        return None
    score_value, passed = row
    if score_value is not None:
        return float(score_value)
    if passed is not None:
        return float(passed)
    return None


