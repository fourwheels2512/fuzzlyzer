async def _audit_async(
    *,
    run_dir: Path,
    run_id: str,
    variant_ids: list[str],
    by_hash: dict[str, Any],
    canonical_eval_rows_by_id: dict[str, dict],
    dims: tuple[str, ...],
    max_cost_usd: float | None,
    max_canonical_evals: int | None,
    judge: Any,
    llm_callable: Any,
    dry_run: bool,
    llm_cache: LLMCache | None = None,
) -> CounterfactualAuditSummary:
    """Phase-1: run counterfactual cells; Phase-2: leave-one-out per flip.

    F7 Phase-2 cache-architecture fix (BACKLOG BLOCKER): when
    ``llm_cache`` is supplied, both Phase-1 (via ``run_variant``) and
    Phase-2 (via the wrapped ``_call_llm`` site) consult it under the
    §7 6-tuple identity. ``default_resolver`` is wired automatically so
    Phase-1 cells cache under the resolver-predicted served version
    (eliminating the canonical/served mismatch warning + cache miss
    that the prior implementation logged on every Gemini call).
    """
    from fuzzeval.costest import cost_for_call

    from topofuzz.runner import (
        NodeOutput,
        _call_llm,
        _default_prompt,
        _extract_text_and_served,
        _extract_usage,
        _safe_resolve,
        default_resolver,
        run_variant,
    )

    results: list[CounterfactualAuditResult] = []
    partial = False
    soft_warn_emitted = False
    consecutive_failures = 0
    n_canonical_pairs = 0
    n_flipping_pairs = 0
    # Pass-1 BLOCKER B1 fix: track TRUE Phase-1 attempt counts so the
    # by_swap_pair / by_dim flip-rate denominators are correct. The
    # prior implementation derived denominators from results[], which
    # only contained Phase-2 (flipping) triples, so flip_rate_pct
    # always collapsed to ~100%.
    n_phase1_attempts_by_swap_pair: dict[tuple[str, str, str], int] = {}
    n_phase1_attempts_by_dim: dict[str, int] = {}
    # F7 BLOCKER fix (counter mismatch): track Phase-1 FLIP counts per
    # swap-pair / per-dim. Prior implementation derived these from
    # Phase-2 ``results[]``; when Phase 2 was cap-hit before any triple
    # finished, the top-level ``n_flipping_pairs`` carried the true
    # Phase-1 count (e.g. 8) while every ``by_dim[*].flipping_pairs``
    # and ``by_swap_pair[*].flipping_pairs`` collapsed to 0 — the same
    # field name carrying inconsistent semantics, surfacing as a
    # contradictory PDF headline ("counterfactuals flipped" + every
    # drilldown row showing 0). These maps are the authoritative
    # numerator: Phase-2 ``results[]`` continues to drive ``by_node``
    # attribution, but the flip COUNT belongs to Phase 1.
    n_flipping_pairs_by_swap_pair: dict[tuple[str, str, str], int] = {}
    n_flipping_pairs_by_dim: dict[str, int] = {}
    # Pass-1 BLOCKER B4 fix: track unpriced re-execution calls so the
    # sidecar can warn that total_cost_usd is a lower bound.
    n_unpriced_calls = 0
    unpriced_models: set[str] = set()
    # F7 Phase-2 cache-architecture fix: track Phase-2 LLM cache hit /
    # miss counts so the CLI / future PDF builder can disclose cache
    # effectiveness. Only the Phase-2 terminal re-exec site is wrapped
    # in this fix; Phase-1 caching is delegated to runner.py's cache
    # accounting (cell.node_outputs[*].cache_hit) and isn't aggregated
    # here. Surfaced via log line at end of pass.
    # Pass-2 RT M3 fix: ``defaultdict(int)`` instead of read-then-write
    # dict so the in-driver increments at the cache-hit / cache-miss
    # sites are single-op (``cache_stats["hits"] += 1``) — read-once
    # semantics make the intent obvious and survive a future
    # ``asyncio.gather`` parallelization of Phase-2 triples without
    # silent undercount on contention.
    from collections import defaultdict
    cache_stats: dict[str, int] = defaultdict(int)

    # Pass-1 BLOCKER B2 fix: cost tracker is a mutable list (1-element)
    # so closures over it see the LIVE total. The prior implementation
    # passed ``cap_hit_cb`` as a closure over a ``nonlocal total_cost``
    # int — and ``total_cost`` was only updated AFTER the whole triple
    # finished. A 5-node topology could blow $0.65 past a $0.30 cap
    # before the next triple's check tripped. The tracker is updated
    # in-place after EACH per-node cost in ``_leave_one_out_for_triple``,
    # so the cap check sees real-time spend.
    cost_tracker: list[float] = [0.0]

    def _cap_hit() -> bool:
        return max_cost_usd is not None and cost_tracker[0] >= max_cost_usd

    # Pass-1 RT MINOR Mi3 fix: thread the most-recent (dim, from, to)
    # swap context into the soft-warn so the operator knows which
    # substitution was in flight when the 80% threshold tripped. The
    # context is updated per Phase-1 cell iteration; the warning
    # reads it inside the closure so a Phase-2-late warning still
    # shows the most-recent Phase-1 cell context. Mutable 1-element
    # dict so the closure sees live updates without ``nonlocal``.
    soft_warn_context: dict[str, str | None] = {
        "dim": None, "from_token": None, "to_token": None,
    }

    def _maybe_soft_warn() -> None:
        nonlocal soft_warn_emitted
        if (
            max_cost_usd is not None
            and not soft_warn_emitted
            and cost_tracker[0] >= 0.80 * max_cost_usd
        ):
            ctx_dim = soft_warn_context["dim"]
            ctx_from = soft_warn_context["from_token"]
            ctx_to = soft_warn_context["to_token"]
            if ctx_dim is not None and ctx_from is not None and ctx_to is not None:
                _log.warning(
                    "audit: cost soft-warn — $%.4f / $%.4f cap (80%%). "
                    "Most recent swap: dim=%s, %s→%s.",
                    cost_tracker[0],
                    max_cost_usd,
                    ctx_dim,
                    ctx_from,
                    ctx_to,
                )
            else:
                # No Phase-1 cell has run yet (defensive — soft-warn at
                # 80% normally fires AFTER some swaps have been
                # attempted). Fall back to the original message shape.
                _log.warning(
                    "audit: cost soft-warn — $%.4f / $%.4f cap (80%%).",
                    cost_tracker[0],
                    max_cost_usd,
                )
            soft_warn_emitted = True

    # Phase 1: generate swaps + run each (variant, canonical_eval,
    # counterfactual_eval) triple. We collect flipping triples for
    # phase 2. Deterministic iteration order: variants in manifest
    # order, canonical evals in eval-file order, dims in request
    # order, swaps in generator order.
    canonical_eval_ids = list(canonical_eval_rows_by_id.keys())
    if max_canonical_evals is not None:
        canonical_eval_ids = canonical_eval_ids[
            : max(0, int(max_canonical_evals))
        ]

    flipping_triples: list[dict[str, Any]] = []

    # Pass-2 MAJOR M2 fix part B: Phase-1 consecutive-failure counter.
    # Mirrors the Phase-2 pattern (a single triple's _MAX_CONSECUTIVE_
    # FAILURES of vendor flakes aborts the pass). Without this, an
    # uncaught vendor SDK exception from ``_run_counterfactual_cell``
    # mid-Phase-1 would crash the whole audit before any sidecar got
    # written.
    phase1_consecutive_failures = 0

    for variant_id in variant_ids:
        if _cap_hit():
            partial = True
            break
        variant_topology = by_hash[variant_id]
        for canonical_eval_id in canonical_eval_ids:
            if _cap_hit():
                partial = True
                break
            canonical_row = canonical_eval_rows_by_id[canonical_eval_id]
            canonical_outputs = _load_cell_outputs(
                run_dir, variant_id, canonical_eval_id
            )
            canonical_score = _load_judge_score(
                run_dir, variant_id, canonical_eval_id
            )
            if canonical_outputs is None or canonical_score is None:
                _log.warning(
                    "audit: source run lacks canonical cell for "
                    "(variant=%s, eval=%s); skipping.",
                    variant_id[:8], canonical_eval_id,
                )
                continue
            for dim in dims:
                if _cap_hit():
                    partial = True
                    break
                # Pass-2 MAJOR M2 fix part A: a hostile canonical_row
                # (e.g. an M9 sentinel collision) makes ``generate_swaps``
                # raise ValueError. The prior implementation let that
                # ValueError unwind the entire audit, dropping every
                # subsequent (variant, eval, dim) pairing. Skip the
                # offending row+dim only; the rest of the matrix
                # continues.
                try:
                    swaps = generate_swaps(canonical_row, dims=(dim,))
                except ValueError as e:
                    _log.warning(
                        "audit: counterfactual generator for dim=%s "
                        "row=%s raised %s: %s; skipping this row's "
                        "swap for this dim.",
                        dim, canonical_eval_id, type(e).__name__, e,
                    )
                    continue
                for swap in swaps:
                    if _cap_hit():
                        partial = True
                        break
                    cf_eval_id = (
                        f"{canonical_eval_id}__{swap.eval_id_suffix}"
                    )
                    cf_row = dict(canonical_row)
                    cf_row["id"] = cf_eval_id
                    cf_row["input"] = swap.counterfactual_input

                    # Run the variant against the counterfactual row.
                    # Pass-2 MAJOR M2 fix part B: vendor SDK exceptions
                    # raised inside ``_run_counterfactual_cell`` (the
                    # runner makes real LLM calls for every node) used
                    # to crash the audit mid-Phase-1. Mirror Phase-2's
                    # consecutive-failure pattern: log + skip the cell,
                    # bump the counter, abort after
                    # ``_MAX_CONSECUTIVE_FAILURES`` cells in a row.
                    try:
                        cf_cell, phase1_cost = await _run_counterfactual_cell(
                            variant_topology=variant_topology,
                            cf_row=cf_row,
                            judge=judge,
                            llm_callable=llm_callable,
                            dry_run=dry_run,
                            run_variant=run_variant,
                            llm_cache=llm_cache,
                            model_served_version_resolver=default_resolver,
                        )
                    except (
                        KeyboardInterrupt,
                        SystemExit,
                        asyncio.CancelledError,
                    ):
                        raise
                    except Exception as e:  # noqa: BLE001 — boundary: vendor SDK
                        _log.warning(
                            "audit: Phase-1 cell failed for "
                            "(variant=%s, canonical=%s, dim=%s, "
                            "swap=%s→%s): %s: %s",
                            variant_id[:8], canonical_eval_id, dim,
                            swap.from_token, swap.to_token,
                            type(e).__name__, e,
                        )
                        phase1_consecutive_failures += 1
                        if (
                            phase1_consecutive_failures
                            >= _MAX_CONSECUTIVE_FAILURES
                        ):
                            raise AuditError(
                                f"audit: {_MAX_CONSECUTIVE_FAILURES} "
                                "consecutive Phase-1 cell failures — "
                                "aborting. This usually indicates a "
                                "programmer bug or sustained vendor "
                                "outage. Last error: "
                                f"{type(e).__name__}: {e}"
                            ) from e
                        continue
                    phase1_consecutive_failures = 0
                    n_canonical_pairs += 1
                    # Pass-1 BLOCKER B1 fix: count every Phase-1 attempt
                    # in the per-swap-pair and per-dim attempt maps. These
                    # are the TRUE denominators for flip_rate_pct.
                    sp_attempt_key = (dim, swap.from_token, swap.to_token)
                    n_phase1_attempts_by_swap_pair[sp_attempt_key] = (
                        n_phase1_attempts_by_swap_pair.get(sp_attempt_key, 0) + 1
                    )
                    n_phase1_attempts_by_dim[dim] = (
                        n_phase1_attempts_by_dim.get(dim, 0) + 1
                    )
                    cost_tracker[0] += phase1_cost
                    # Pass-1 RT MINOR Mi3 fix: update the soft-warn
                    # context BEFORE calling _maybe_soft_warn so the
                    # warning carries the current swap's (dim, from, to)
                    # tokens if it fires on this cell.
                    soft_warn_context["dim"] = dim
                    soft_warn_context["from_token"] = swap.from_token
                    soft_warn_context["to_token"] = swap.to_token
                    _maybe_soft_warn()

                    cf_score = (
                        cf_cell.judge_result.value
                        if cf_cell.judge_result is not None
                        else None
                    )
                    if cf_score is None:
                        _log.warning(
                            "audit: Phase-1 cell for variant=%s "
                            "canonical_eval=%s dim=%s produced no "
                            "judge result; skipping leave-one-out.",
                            variant_id[:8], canonical_eval_id, dim,
                        )
                        continue

                    # Did the verdict flip? Binarised via threshold.
                    canonical_binary = canonical_score >= _VERDICT_THRESHOLD
                    cf_binary = cf_score >= _VERDICT_THRESHOLD
                    if canonical_binary == cf_binary:
                        # No flip → no Phase-2 work for this triple.
                        continue

                    n_flipping_pairs += 1
                    # F7 BLOCKER fix: increment Phase-1 flip counts at
                    # the same site as n_flipping_pairs so by_swap_pair
                    # and by_dim carry the Phase-1 truth even when
                    # Phase 2 is cap-hit. Without this, the published
                    # PDF could lead with "counterfactuals flipped"
                    # while every drilldown row showed 0 flips.
                    sp_flip_key = (dim, swap.from_token, swap.to_token)
                    n_flipping_pairs_by_swap_pair[sp_flip_key] = (
                        n_flipping_pairs_by_swap_pair.get(sp_flip_key, 0) + 1
                    )
                    n_flipping_pairs_by_dim[dim] = (
                        n_flipping_pairs_by_dim.get(dim, 0) + 1
                    )
                    flipping_triples.append(
                        {
                            "variant_id": variant_id,
                            "canonical_eval_id": canonical_eval_id,
                            "cf_eval_id": cf_eval_id,
                            "cf_row": cf_row,
                            "dim": dim,
                            "from_token": swap.from_token,
                            "to_token": swap.to_token,
                            "cf_outputs": [
                                _node_output_to_dict(o)
                                for o in cf_cell.node_outputs
                            ],
                            "canonical_outputs": canonical_outputs,
                            "canonical_score": canonical_score,
                            "cf_score": cf_score,
                            "variant_topology": variant_topology,
                        }
                    )

    # Phase 2: leave-one-out for each flipping triple.
    for triple in flipping_triples:
        if _cap_hit():
            partial = True
            break
        # Pass-1 BLOCKER B2 fix: pass the shared cost_tracker into the
        # per-triple driver so it can update spend AFTER EACH per-node
        # cost (not just after the whole triple). Pass-1 BLOCKER B4 fix:
        # also pass mutable unpriced-call counters so the per-node loop
        # can flag terminal re-execs against models missing from the
        # rate table.
        unpriced_state = {
            "count": n_unpriced_calls,
            "models": unpriced_models,
        }
        triple_results, consecutive_failures = (
            await _leave_one_out_for_triple(
                triple=triple,
                judge=judge,
                llm_callable=llm_callable,
                dry_run=dry_run,
                _call_llm=_call_llm,
                _default_prompt=_default_prompt,
                _extract_text_and_served=_extract_text_and_served,
                _extract_usage=_extract_usage,
                _safe_resolve=_safe_resolve,
                NodeOutput=NodeOutput,
                cost_for_call=cost_for_call,
                consecutive_failures=consecutive_failures,
                cap_hit_cb=_cap_hit,
                cost_tracker=cost_tracker,
                unpriced_state=unpriced_state,
                llm_cache=llm_cache,
                model_served_version_resolver=default_resolver,
                cache_stats=cache_stats,
            )
        )
        n_unpriced_calls = unpriced_state["count"]
        # ``unpriced_models`` is the same set object so .add() inside
        # the triple driver already reflects.
        results.extend(triple_results)
        _maybe_soft_warn()
        # If the per-triple driver short-circuited mid-flight on the
        # cap, mark partial — same shape as the prior implementation.
        if _cap_hit():
            partial = True

    # F7 Phase-2 cache-architecture fix: log cache effectiveness once
    # per pass so operators can see whether warm reruns are actually
    # amortizing. Skipped when no cache is wired (the historical
    # behavior; nothing to report).
    if llm_cache is not None:
        total_lookups = cache_stats["hits"] + cache_stats["misses"]
        if total_lookups > 0:
            hit_rate_pct = (cache_stats["hits"] / total_lookups) * 100.0
            _log.info(
                "audit: Phase-2 terminal re-exec cache — %d hits, %d "
                "misses (%.1f%% hit rate across %d lookups).",
                cache_stats["hits"],
                cache_stats["misses"],
                hit_rate_pct,
                total_lookups,
            )

    summary = _aggregate(
        results=tuple(results),
        dims=dims,
        n_canonical_pairs=n_canonical_pairs,
        n_flipping_pairs=n_flipping_pairs,
        total_cost=cost_tracker[0],
        partial=partial,
        # Pass-1 BLOCKER B1 fix: thread the Phase-1 attempt maps so
        # _aggregate uses them as flip-rate denominators.
        n_phase1_attempts_by_swap_pair=n_phase1_attempts_by_swap_pair,
        n_phase1_attempts_by_dim=n_phase1_attempts_by_dim,
        # F7 BLOCKER fix: thread the Phase-1 FLIP maps so _aggregate
        # uses them as the authoritative numerator on by_swap_pair /
        # by_dim. Without these, partial Phase-2 runs surface a
        # contradictory PDF where the top-level n_flipping_pairs
        # disagrees with every per-dim / per-swap row.
        n_flipping_pairs_by_swap_pair=n_flipping_pairs_by_swap_pair,
        n_flipping_pairs_by_dim=n_flipping_pairs_by_dim,
        # Pass-1 BLOCKER B4 fix: thread unpriced-call accounting.
        unpriced_call_count=n_unpriced_calls,
        unpriced_models=tuple(sorted(unpriced_models)),
        # Pass-RT-B1 fix: persist dry_run into the sidecar so publish
        # can refuse to render procurement PDFs off stub data.
        dry_run=dry_run,
    )
    _write_audit_sidecar(run_dir, summary)
    return summary


