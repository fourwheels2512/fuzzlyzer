"""§11a standalone-verifier proof: the ~30-line ``verify_dsse.py``
documented in SECURITY.md must verify the committed v0.5 fixture and
must reject single-byte tampering.

The script is extracted from the first fenced ``python`` block in
SECURITY.md so the documented code IS the tested code — no risk of
the docs drifting from a separate copy. The fixture lives under
``packages/topofuzz/tests/fixtures/signed/`` and is regenerated by
``packages/topofuzz/tests/fixtures/signed/_regen.py``; the matching
public key is committed at ``keys/dev.pub.pem`` (the blueprint-literal
publication path per §17a).

These tests run the extracted script in a subprocess (the script
calls ``sys.exit`` so we cannot import it inline) and assert:

1. Against the unmodified fixture, exit 0 and stdout contains the
   authenticated payload bytes.
2. After flipping one byte of the envelope's base64 payload, exit
   nonzero with no payload on stdout.
3. The fenced block has the documented ≤30-line budget.
"""

from __future__ import annotations

import base64
import json
import re
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
SECURITY_MD = REPO_ROOT / "SECURITY.md"
PUBKEY = REPO_ROOT / "keys" / "dev.pub.pem"
FIXTURE_ENVELOPE = (
    REPO_ROOT
    / "packages"
    / "topofuzz"
    / "tests"
    / "fixtures"
    / "signed"
    / "attestation.json"
)

# Per BLUEPRINT_v5plus.md §14 line 392: "30-line verify_dsse.py reference
# script". The fenced block today is 27 lines (script + 4 leading comment
# lines); 32 leaves ~5 lines of breathing room for a future shebang or
# clarifying comment without hiding a meaningful body growth. Lift this
# explicitly with a comment if the script grows beyond ~30 deliberately —
# the value prop of a reference verifier is "auditable in one screen."
LINE_COUNT_CEILING = 32


def _extract_verify_dsse_script() -> str:
    """Return the verify_dsse.py reference script from SECURITY.md.

    Finds the ```python``` fenced block whose body contains ``"DSSEv1"``
    (the unique PAE prefix). This is content-anchored rather than
    position-anchored so a future PR adding an unrelated python snippet
    earlier in the file (e.g. a CLI usage example) doesn't silently
    cause this test to measure the wrong block — RT pass-1 M-1.

    Raises ``RuntimeError`` if zero or more-than-one fenced blocks
    contain ``"DSSEv1"``. Fail-closed is deliberate: ambiguity here
    means the doc layout shifted in a way the tests need to confirm.
    """
    md = SECURITY_MD.read_text(encoding="utf-8")
    candidates = re.findall(r"```python\n(.+?)```", md, re.DOTALL)
    matches = [c for c in candidates if "DSSEv1" in c]
    if len(matches) != 1:
        raise RuntimeError(
            f"SECURITY.md at {SECURITY_MD} contains {len(matches)} python "
            f"fenced blocks with 'DSSEv1' (expected exactly 1; the "
            f"reference verifier moved, was duplicated, or was deleted)."
        )
    return matches[0]


@pytest.fixture(scope="module")
def verify_script(tmp_path_factory: pytest.TempPathFactory) -> Path:
    """Materialize the SECURITY.md python block as an executable file."""
    src = _extract_verify_dsse_script()
    out_dir = tmp_path_factory.mktemp("security-md-script")
    path = out_dir / "verify_dsse.py"
    path.write_text(src, encoding="utf-8")
    return path


def test_security_md_contains_python_block() -> None:
    """The reference script is present and reachable via the extractor.
    A regression here means SECURITY.md lost the only ``DSSEv1`` python
    fence (or grew a second one without the test updating to disambiguate)."""
    src = _extract_verify_dsse_script()
    # _extract_verify_dsse_script already requires "DSSEv1" — these
    # assertions cover the *shape* of the block (cryptographic essentials)
    # so a future PR that strips the import or the PAE construction is
    # flagged here, not on a downstream subprocess timeout.
    assert "DSSEv1" in src
    assert "load_pem_public_key" in src, "extracted block is missing the PEM load"
    assert "InvalidSignature" in src, "extracted block does not handle InvalidSignature"


def test_script_line_count_under_ceiling() -> None:
    """The fenced block stays under :data:`LINE_COUNT_CEILING` lines so
    the reference verifier remains a *reference* — short enough to read
    in one sitting."""
    src = _extract_verify_dsse_script()
    n_lines = src.count("\n")
    assert n_lines <= LINE_COUNT_CEILING, (
        f"SECURITY.md verify_dsse.py grew to {n_lines} lines "
        f"(ceiling: {LINE_COUNT_CEILING}). If the extra lines are "
        f"genuinely necessary, lift the ceiling deliberately and "
        f"document why in this test."
    )


def test_verify_passes_on_unmodified_fixture(verify_script: Path) -> None:
    """The script verifies the committed v0.5 fixture and prints the
    authenticated payload bytes to stdout."""
    result = subprocess.run(
        [sys.executable, str(verify_script), str(FIXTURE_ENVELOPE), str(PUBKEY)],
        capture_output=True,
        timeout=60,
    )
    assert result.returncode == 0, (
        f"verify_dsse.py exited {result.returncode} on the unmodified "
        f"fixture.\nstdout: {result.stdout!r}\nstderr: {result.stderr!r}"
    )
    # Stdout must be the authenticated payload bytes — at minimum, valid
    # JSON containing our fixture run_id (a load-bearing assertion: a
    # buggy script could pass exit 0 while printing nothing).
    payload = json.loads(result.stdout)
    assert payload["run_id"] == "fixture-v0.5"
    assert payload["schema_version"] == 1


def test_verify_rejects_single_byte_tamper(
    verify_script: Path,
    tmp_path: Path,
) -> None:
    """Flip one byte of the base64 payload; the script must exit nonzero
    and emit no payload on stdout. This is the BLUEPRINT_v5plus.md §15
    DoD line 436 contract ("Tampering with one byte of the payload
    returns exit 1") applied to the reference verifier."""
    import string

    envelope = json.loads(FIXTURE_ENVELOPE.read_bytes())
    payload_b64 = envelope["payload"]
    # Find a content-character index (not '=' padding, not '+'/'/' which
    # are alphabet-edge) to swap. RT pass-1 N-1: a future fixture regen
    # could place padding at index 1, corrupting base64 length-grammar
    # rather than the decoded bytes — the test would still pass but for
    # the wrong reason (binascii decode failure, not signature failure).
    alphanumeric = set(string.ascii_letters + string.digits)
    flip_idx = next(
        i for i, c in enumerate(payload_b64) if c in alphanumeric
    )
    original = payload_b64[flip_idx]
    # Pick a definitely-different base64 alphabet character. "A" always
    # differs from any other alphanumeric; we pick "B" instead so a fresh
    # fixture whose first content char happens to be "A" still flips.
    replacement = "B" if original != "B" else "C"
    tampered_b64 = (
        payload_b64[:flip_idx] + replacement + payload_b64[flip_idx + 1 :]
    )
    # Sanity: the tampered base64 still decodes (so the script reaches
    # the signature check), but to different bytes than the signature
    # was computed over.
    assert base64.b64decode(tampered_b64, validate=True) != base64.b64decode(
        payload_b64, validate=True
    )
    envelope["payload"] = tampered_b64
    bad = tmp_path / "attestation.tampered.json"
    bad.write_text(json.dumps(envelope), encoding="utf-8")

    result = subprocess.run(
        [sys.executable, str(verify_script), str(bad), str(PUBKEY)],
        capture_output=True,
        timeout=60,
    )
    assert result.returncode != 0, (
        f"verify_dsse.py incorrectly accepted a tampered envelope. "
        f"stdout: {result.stdout!r}, stderr: {result.stderr!r}"
    )
    # No payload should have been printed (the script writes payload
    # only on the success path).
    assert result.stdout == b"", (
        f"tampered envelope produced stdout: {result.stdout!r} — "
        f"the script should write payload only on signature success"
    )


def test_fixture_pubkey_matches_envelope_keyid() -> None:
    """A guard against a regen accident where the fixture's envelope and
    the committed pubkey drift out of sync — verify would still PASS
    if the test happened to use a stale pubkey, but the published key
    on disk wouldn't match what shipped in the envelope."""
    envelope = json.loads(FIXTURE_ENVELOPE.read_bytes())
    sig_entry = envelope["signatures"][0]
    assert sig_entry["keyid"] == "topofuzz-dev-v0.5", (
        f"fixture envelope keyid drifted to {sig_entry['keyid']!r}; "
        f"if you bumped Ed25519Signer.keyid, regenerate the fixture "
        f"via packages/topofuzz/tests/fixtures/signed/_regen.py"
    )
    # And confirm the committed pubkey loads as Ed25519.
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PublicKey,
    )
    from cryptography.hazmat.primitives.serialization import (
        load_pem_public_key,
    )

    pub = load_pem_public_key(PUBKEY.read_bytes())
    assert isinstance(pub, Ed25519PublicKey)
